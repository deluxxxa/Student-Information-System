    private void jButton_UpdateStudentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_UpdateStudentActionPerformed
        if (validateInputs()) {
            Model.Student stu = new Model.Student(
            jTextField_IDnumber.getText(), jTextField_name.getText(), jTextField_email.getText(),
            jComboBox_gender.getSelectedItem().toString(), jComboBox_course.getSelectedItem().toString(),
            jComboBox_year.getSelectedItem().toString()
            );
            new DAO.StudentDAO().updateStudent(stu);
            jButton_RefreshActionPerformed(null);
        }
    }//GEN-LAST:event_jButton_UpdateStudentActionPerformed

    private void jButton_AddNewStudentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_AddNewStudentActionPerformed
        
        String name = jTextField_name.getText().trim();
        
        if (validateInputs()) {
            
            DAO.StudentDAO dao = new DAO.StudentDAO();
            if (dao.isNameDuplicate(name)) {
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "Error: A student with the name '" + name + "' already exists.", 
                    "Duplicate Entry", 
                    javax.swing.JOptionPane.ERROR_MESSAGE);
                return; // Stop the process so the student isn't added
            }
            
            Model.Student stu = new Model.Student(
                jTextField_IDnumber.getText(), jTextField_name.getText(), jTextField_email.getText(),
                jComboBox_gender.getSelectedItem().toString(), jComboBox_course.getSelectedItem().toString(),
                jComboBox_year.getSelectedItem().toString()
            );
            dao.insertStudent(stu);
            jButton_RefreshActionPerformed(null);
            javax.swing.JOptionPane.showMessageDialog(this, "Student added successfully!");
        }
    }//GEN-LAST:event_jButton_AddNewStudentActionPerformed

    private void jButton_DeleteStudentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_DeleteStudentActionPerformed
        String id = jTextField_IDnumber.getText();
        if(!id.isEmpty()){
            new DAO.StudentDAO().deleteStudent(id);
            jButton_RefreshActionPerformed(null);
            jButton_ClearActionPerformed(null);
        } else {
        // Simple popup message when no ID is found in the text field
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Please select a student from the table to delete.", 
            "No Selection", 
            javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButton_DeleteStudentActionPerformed

    private void jButton_SearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_SearchActionPerformed
        // READ and SEARCH
        String query = jTextField_SearchStudent.getText();
        if (query.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a search term.", "Search Error", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        jTable_StudentInformation.setModel(new DAO.StudentDAO().searchStudents(query));
    }//GEN-LAST:event_jButton_SearchActionPerformed

