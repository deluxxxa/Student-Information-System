    private boolean validateInputs() {
        
        String id = jTextField_IDnumber.getText().trim();
        String name = jTextField_name.getText().trim();
        String email = jTextField_email.getText().trim();

        // Check for empty fields
        if (id.isEmpty() || name.isEmpty() || email.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please fill out all required fields (ID, Name, and Email).", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return false;
        }

        // Check ID length (must be at least 10 characters/numbers)
        if (id.length() < 10) {
            javax.swing.JOptionPane.showMessageDialog(this, "Invalid ID Number: Must be at least 10 characters long.", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return false;
        }
        
        return true;
    }
    
